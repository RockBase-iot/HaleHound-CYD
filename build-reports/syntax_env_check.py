#!/usr/bin/env python3
"""Env-accurate `-fsyntax-only` check for HaleHound-CYD translation units.

Why this exists
---------------
`pio run` cannot complete inside the agent sandbox. The bulk-delete guard
budgets 50 file deletions per tool call, and PlatformIO's package manager
exceeds that before the first `Compiling` line (it wants to drop 912 entries
under `.pio/build`). The same guard blocks the platform/package refresh.
That is an environmental limit, not a code error.

This script is the documented fallback. It drives the *real* target toolchain
with the *real* flags:

* `nm-cyd-c5` (ESP32-C5, RISC-V) -- `[env]` pins pioarduino 55.03.32, whose
  split `framework-arduinoespressif32-libs/<chip>/flags/` directory holds the
  authoritative `includes`, `defines` and `cpp_flags` generated by the
  unified-arduino builder. 289 `-iwithprefixbefore` entries = the exact
  ESP-IDF include set, so nothing has to be guessed or iterated on.
* `esp32-cyd` (ESP32, Xtensa) -- `espressif32@6.9.0` uses the pre-split
  framework, so headers come from `framework-arduinoespressif32/tools/sdk/`.

Windows caps a command line at ~32 KB and the ESP32 include set blows past
that, so every include is emitted as `-iwithprefixbefore` underneath a single
`-iprefix` root (the same trick ESP-IDF itself uses to stay short).

Not covered: linking, `extra_scripts`, `build_src_filter`. Linking of the
pure-logic layer is covered separately (xtensa `ld -r` + symbol audit).

Usage
-----
    python build-reports/syntax_env_check.py                 # default targets
    python build-reports/syntax_env_check.py src/ui/Foo.cpp
    python build-reports/syntax_env_check.py --env esp32-cyd
    python build-reports/syntax_env_check.py --tests --std gnu++17
"""

