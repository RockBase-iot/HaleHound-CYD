def _split_flags(text: str) -> list[str]:
    """Tokenise a flags file, honouring quotes."""
    out: list[str] = []
    cur, quote = "", None
    for ch in text:
        if quote:
            if ch == quote:
                quote = None
            else:
                cur += ch
        elif ch in "\"'":
            quote = ch
        elif ch.isspace():
            if cur:
                out.append(cur)
                cur = ""
        else:
            cur += ch
    if cur:
        out.append(cur)
    return out


def _walk_dirs(root: Path) -> list[Path]:
    out: list[Path] = []
    for dirpath, dirs, _ in os.walk(root):
        if any(s in dirpath.lower() for s in SKIP_LEAF):
            dirs[:] = []
            continue
        out.append(Path(dirpath))
    return out


def _compact(includes: list[Path]) -> tuple[list[str], Path | None]:
    """Split includes into (relative-to-prefix, absolute).

    Every include is emitted as `-iwithprefixbefore <rel>` under one
    `-iprefix` root -- the same trick ESP-IDF uses -- because Windows caps a
    command line at ~32 KB and the raw ESP32 include set is far past that.
    The prefix is picked to *minimise the total emitted length*, not by hit
    count: a shallow prefix such as the repo root covers more entries but
    leaves every relative path long enough to blow the limit anyway.
    """
    counts: dict[Path, int] = {}
    for p in includes:
        for parent in p.parents:
            counts[parent] = counts.get(parent, 0) + 1

    best: tuple[int, Path] | None = None
    for cand, hits in counts.items():
        if hits < 8:
            continue
        total = 0
        for p in includes:
            if cand in p.parents or p == cand:
                total += len(str(p.relative_to(cand))) + 22  # -iwithprefixbefore "..."\n
            else:
                total += len(str(p)) + 6                      # -I"..."\n
        if best is None or total < best[0]:
            best = (total, cand)

    if best is None:
        return [], None
    prefix = best[1]
    rel = [p for p in includes if prefix in p.parents or p == prefix]
    if prefix in rel:
        rel.remove(prefix)
    return [str(p.relative_to(prefix)).replace("\\", "/") for p in rel], prefix


def prepare(env: str, std: str | None, targets: list[str]):
    cfg = ENV[env]
    gxx: Path = cfg["gxx"]
    fw: Path = cfg["fw"]
    libs_base: Path | None = cfg.get("libs")
    project = [ROOT, ROOT / "include", ROOT / "src", ROOT / "boards", ROOT / "boards" / cfg["variant"]]
    if any(t.startswith("test/") or "hostcheck" in t for t in targets):
        project.append(ROOT / "scripts" / "hostcheck" / "unity")

    if cfg.get("legacy"):
        sdk_inc = fw / "tools/sdk" / cfg["chip"] / "include"
        cpp = ["-std=gnu++17", "-fno-rtti", "-fexceptions", "-fsyntax-only", "-w"]
        includes = [sdk_inc, fw / "cores" / "esp32", fw / "variants" / cfg["variant"]]
        includes.append(sdk_inc.parent / cfg["mem"] / "include")  # sdkconfig.h
        includes += _walk_dirs(sdk_inc)
        defines = [f"-D{d}" for d in PROJECT_DEFINES if not d.startswith(DROP_PREFIX)]
        defines += [f"-D{d}" for d in cfg["extra_defines"]]
    else:
        base = libs_base / cfg["chip"]
        flags_dir = base / "flags"
        toks = _split_flags((flags_dir / "includes").read_text())
        includes = []
        i = 0
        while i < len(toks):
            tok = toks[i]
            if tok == "-iwithprefixbefore" and i + 1 < len(toks):
                includes.append(base / "include" / toks[i + 1])
                i += 2
                continue
            if tok.startswith("-I"):
                includes.append(Path(tok[2:]))
            i += 1
        includes.append(base / cfg["mem"] / "include")
        includes += [fw / "cores" / "esp32", fw / "variants" / cfg["variant"]]
        cpp = [f for f in _split_flags((flags_dir / "cpp_flags").read_text())
               if not f.startswith("-std=")]
        cpp += ["-std=gnu++2a", "-fsyntax-only", "-w"]
        defines = [f"-D{d}" for d in PROJECT_DEFINES + cfg["extra_defines"]]
        defines += _split_flags((flags_dir / "defines").read_text())

    libdeps = CORE / "libdeps" / env
    if libdeps.is_dir():
        for lib in sorted(libdeps.iterdir()):
            if lib.is_dir():
                includes.append(lib)
                if (lib / "src").is_dir():
                    includes.append(lib / "src")

    # Framework-bundled Arduino libraries (SPI, SD, WiFi, BLE, EEPROM, FS, ...).
    # Needed for the legacy single-TU app, which pulls them in directly.
    bundled = fw / "libraries"
    if bundled.is_dir():
        for lib in sorted(bundled.iterdir()):
            if (lib / "src").is_dir():
                includes.append(lib / "src")

    # Anything the build system generated (chip back-compat headers, sdkconfig
    # shims) lands here.
    gen = CORE / "build" / env
    if gen.is_dir():
        includes.append(gen)

    includes += project

    # platformio.ini force-includes User_Setup.h (with USER_SETUP_LOADED set),
    # which is where LOAD_GFXFF lives. Without it TFT_eSPI never declares
    # GFXfont and nosifer_font.h fails in a way the real build never sees.
    setup_h = ROOT / "include" / "User_Setup.h"
    if setup_h.is_file():
        cpp += ["-include", str(setup_h)]

    if std:
        cpp = [f for f in cpp if not f.startswith("-std=")] + [f"-std={std}"]

    seen: set[str] = set()
    uniq: list[Path] = []
    for p in includes:
        k = str(p).lower()
        if k in seen or not p.is_dir():
            continue
        seen.add(k)
        uniq.append(p)

    rel, prefix = _compact(uniq)
    abs_dirs = [p for p in uniq if prefix is None or (prefix not in p.parents and p != prefix)]

    body: list[str] = []
    if prefix is not None:
        body.append('-iprefix "%s/"' % str(prefix).replace("\\", "/"))
        body += ['-iwithprefixbefore "%s"' % r for r in rel]
    body += ['-I"%s"' % str(p).replace("\\", "/") for p in abs_dirs]

    rsp = ROOT / "build-reports" / f"_syntax_{env}.rsp"
    rsp.write_text("\n".join(body) + "\n", encoding="ascii")
    clen = sum(len(d) + 3 for d in defines) + 160
    meta = f"includes={len(uniq)} (prefix-compacted {len(rel)})  defines={len(defines)}  " \
           f"rsp={rsp.name}({rsp.stat().st_size}B)  cmdline~{clen}B"
    return rsp, defines, cpp, meta


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="*")
    ap.add_argument("--env", default="nm-cyd-c5", choices=sorted(ENV))
    ap.add_argument("--std", default=None, help="override -std (e.g. gnu++17)")
    ap.add_argument("--tests", action="store_true", help="the 4 new suites + unity shim")
    ap.add_argument("--baseline", action="store_true",
                    help="check untouched files; same failures => tool artifact, not regression")
    args = ap.parse_args()

    if args.files:
        targets = args.files
    elif args.tests:
        targets = TEST_TARGETS
    elif args.baseline:
        targets = BASELINE_TARGETS
    else:
        targets = DEFAULT_TARGETS
    gxx = ENV[args.env]["gxx"]
    if not gxx.exists():
        sys.exit(f"missing toolchain: {gxx}")

    rsp, defines, cpp, meta = prepare(args.env, args.std, targets)

    print(f"env={args.env}  toolchain={gxx.name}")
    print(f"  {meta}")
    print("-" * 74)

    bad = 0
    for t in targets:
        src = ROOT / t
        if not src.exists():
            print(f"MISSING      {t}")
            bad += 1
            continue
        r = subprocess.run([str(gxx), *cpp, *defines, f"@{rsp}", str(src)],
                           capture_output=True, text=True, errors="replace")
        out = (r.stdout + r.stderr).strip()
        if r.returncode == 0 and not out:
            print(f"PASS         {t}")
        else:
            bad += 1
            lines = [ln for ln in out.splitlines() if "error" in ln.lower()] or out.splitlines()
            print(f"FAIL({r.returncode})     {t}")
            for ln in lines[:5]:
                print("   " + ln.strip()[:155])
    print("-" * 74)
    print(f"{len(targets) - bad}/{len(targets)} clean")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
